using Microsoft.Build.Utilities.ProjectCreation;

namespace Chirograph.Tests.Scaffolding;

/// <summary>The generators an <c>OpenApiClient</c> item can name.</summary>
public enum Generator
{
    /// <summary>Kiota: a client class, <c>RocketsClient</c>.</summary>
    Kiota,

    /// <summary>Refitter: a Refit interface, <c>IRocketsClient</c>.</summary>
    Refitter,
}

/// <summary>
/// The throwaway application of the OpenAPI client tests: it declares the client <c>RocketsClient</c> in <c>Throwaway.Clients</c>,
/// registers it on a plain <c>Host.CreateApplicationBuilder</c> with the generated <c>AddRocketsClient()</c> (no Dovetail), and asks
/// <see cref="RocketsApi" /> for one rocket.
/// </summary>
internal static class RocketsApp
{
    /// <summary>The environment that points the client at <paramref name="api" />.</summary>
    public static Dictionary<string, string> Environment(RocketsApi api) => new() { ["Clients__RocketsClient__BaseAddress"] = api.BaseAddress.ToString() };

    /// <summary>Declares the client <c>RocketsClient</c>, generated by <paramref name="generator" /> from <paramref name="include" />.</summary>
    public static ProjectCreator OpenApiClient(
        this ProjectCreator project,
        Generator generator,
        string include,
        string clientName = "RocketsClient",
        IReadOnlyDictionary<string, string?>? metadata = null
    ) =>
        project.ItemInclude(
            "OpenApiClient",
            include,
            metadata: new Dictionary<string, string?>
            {
                ["Generator"] = generator.ToString(),
                ["ClientName"] = clientName,
                ["Namespace"] = "Throwaway.Clients",
            }.Concat(metadata ?? new Dictionary<string, string?>()).ToDictionary()
        );

    /// <summary>References Microsoft.Extensions.Hosting at the version the repository pins for <paramref name="targetFramework" />.</summary>
    public static ProjectCreator Hosting(this ProjectCreator project, string targetFramework) =>
        project.ItemPackageReference("Microsoft.Extensions.Hosting", Config.CentralPackageVersion("Microsoft.Extensions.Hosting", targetFramework));

    /// <summary>
    /// Adds <c>app/app.csproj</c>, a Chirograph consumer that generates <c>RocketsClient</c> with <paramref name="generator" /> from
    /// <paramref name="include" /> (<c>app/rockets.json</c> unless it says otherwise) with more <paramref name="metadata" />, and its
    /// <c>Program.cs</c>.
    /// </summary>
    public static SdkTestProject AddRocketsApp(
        this SdkTestProject project,
        string targetFramework,
        Generator generator,
        string include = "rockets.json",
        IReadOnlyDictionary<string, string?>? metadata = null
    ) =>
        project
           .AddProject("app/app.csproj", project.CreateConsumer().Hosting(targetFramework).OpenApiClient(generator, include, metadata: metadata))
           .AddFile("app/rockets.json", RocketsApi.Document)
           .AddFile("app/Program.cs", Program(generator));

    /// <summary>The application: it registers the client, resolves it and writes the rocket it gets.</summary>
    public static string Program(Generator generator) => generator switch
    {
        Generator.Kiota => KiotaProgram,
        Generator.Refitter => RefitterProgram,
        _ => throw new ArgumentOutOfRangeException(nameof(generator), generator, null),
    };

    private const string KiotaProgram = $$"""
        using System;
        using Microsoft.Extensions.DependencyInjection;
        using Microsoft.Extensions.Hosting;
        using Microsoft.Extensions.Logging;
        using Throwaway.Clients;

        var builder = Host.CreateApplicationBuilder(args);
        builder.Logging.ClearProviders();
        builder.Services.AddRocketsClient();
        using var host = builder.Build();
        var client = host.Services.GetRequiredService<RocketsClient>();
        var rocket = await client.Rockets[Guid.Parse("{{RocketsApi.RocketId}}")].GetAsync();
        Console.WriteLine($"{client.GetType().Name}: {rocket!.Id} {rocket.SerialNumber}");
        """;

    private const string RefitterProgram = $$"""
        using System;
        using Microsoft.Extensions.DependencyInjection;
        using Microsoft.Extensions.Hosting;
        using Microsoft.Extensions.Logging;
        using Throwaway.Clients;

        var builder = Host.CreateApplicationBuilder(args);
        builder.Logging.ClearProviders();
        builder.Services.AddRocketsClient();
        using var host = builder.Build();
        var client = host.Services.GetRequiredService<IRocketsClient>();
        var rocket = await client.GetRocket(Guid.Parse("{{RocketsApi.RocketId}}"));
        Console.WriteLine($"{nameof(IRocketsClient)}: {rocket.Id} {rocket.SerialNumber}");
        """;
}
