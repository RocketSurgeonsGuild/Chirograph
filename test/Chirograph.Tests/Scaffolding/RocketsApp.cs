using Microsoft.Build.Utilities.ProjectCreation;

namespace Chirograph.Tests.Scaffolding;

/// <summary>The generators an <c>OpenApiClient</c> item can name.</summary>
public enum Generator
{
    /// <summary>Kiota: a client class, <c>RocketsClient</c>.</summary>
    Kiota,

    /// <summary>Refitter: a Refit interface, <c>IRocketsClient</c>.</summary>
    Refitter,
}

/// <summary>
/// The throwaway application of the OpenAPI client tests: it declares the client <c>RocketsClient</c> in <c>Throwaway.Clients</c>,
/// registers it on a plain <c>Host.CreateApplicationBuilder</c> with the generated <c>AddRocketsClient()</c> (no Dovetail), and asks
/// <see cref="RocketsApi" /> for one rocket.
/// </summary>
internal static class RocketsApp
{
    /// <summary>The environment that points the client at <paramref name="api" />.</summary>
    public static Dictionary<string, string> Environment(RocketsApi api) => new() { ["Clients__RocketsClient__BaseAddress"] = api.BaseAddress.ToString() };

    /// <summary>Declares the client <c>RocketsClient</c>, generated by <paramref name="generator" /> from <paramref name="include" />.</summary>
    public static ProjectCreator OpenApiClient(
        this ProjectCreator project,
        Generator generator,
        string include,
        string clientName = "RocketsClient",
        IReadOnlyDictionary<string, string?>? metadata = null,
        bool hook = true
    )
    {
        // metadata wins over the defaults, and a null leaves the metadata out (Namespace = null falls back to $(RootNamespace))
        var all = new Dictionary<string, string?>
        {
            ["Generator"] = generator.ToString(),
            ["ClientName"] = clientName,
            ["Namespace"] = "Throwaway.Clients",
        };
        foreach (var (name, value) in metadata ?? new Dictionary<string, string?>())
        {
            all[name] = value;
        }

        project.ItemInclude("OpenApiClient", include, metadata: all);
        return hook ? project.Hook(generator, clientName, all["Namespace"]) : project;
    }

    /// <summary>
    /// The implementation of the hook every client project must have, <c>CreateRequestAdapter</c> (Kiota) or <c>CreateRefitSettings</c>
    /// (Refitter), that returns what it is given: written to <c>obj</c> and compiled before <c>CoreCompile</c>, so the project needs no file.
    /// The namespace is <paramref name="namespace" />, or <c>$(RootNamespace)</c> when it is <c>null</c>.
    /// </summary>
    public static ProjectCreator Hook(this ProjectCreator project, Generator generator, string clientName = "RocketsClient", string? @namespace = null)
    {
        var file = $"$(IntermediateOutputPath){clientName}.Hook.cs";
        // %3B is a semicolon: WriteLinesToFile would split the line on one
        var code = $"namespace {@namespace ?? "$(RootNamespace)"}%3B public static partial class {clientName}ServiceCollectionExtensions {{ "
          + HookMember(generator).Replace(";", "%3B", StringComparison.Ordinal)
          + " }";
        return project
              .Target($"_ThrowawayHook{clientName}", beforeTargets: "CoreCompile")
              .Task(
                   "WriteLinesToFile",
                   parameters: new Dictionary<string, string?> { ["File"] = file, ["Lines"] = code, ["Overwrite"] = "true", ["WriteOnlyWhenDifferent"] = "true" }
               )
              .TargetItemInclude("Compile", file);
    }

    /// <summary>The implementation of the hook of <paramref name="generator" />'s registration that returns what it is given.</summary>
    public static string HookMember(Generator generator) => generator switch
    {
        Generator.Kiota =>
            "private static partial global::Microsoft.Kiota.Abstractions.IRequestAdapter CreateRequestAdapter(global::System.IServiceProvider services, global::Microsoft.Kiota.Http.HttpClientLibrary.HttpClientRequestAdapter adapter) => adapter;",
        Generator.Refitter =>
            "private static partial global::Refit.RefitSettings? CreateRefitSettings(global::System.IServiceProvider services, global::Refit.RefitSettings? settings) => settings;",
        _ => throw new ArgumentOutOfRangeException(nameof(generator), generator, null),
    };

    /// <summary>References Microsoft.Extensions.Hosting at the version the repository pins for <paramref name="targetFramework" />.</summary>
    public static ProjectCreator Hosting(this ProjectCreator project, string targetFramework) =>
        project.ItemPackageReference("Microsoft.Extensions.Hosting", Config.CentralPackageVersion("Microsoft.Extensions.Hosting", targetFramework));

    /// <summary>
    /// Adds <c>app/app.csproj</c>, a Chirograph consumer that generates <c>RocketsClient</c> with <paramref name="generator" /> from
    /// <paramref name="include" /> (<c>app/rockets.json</c> unless it says otherwise) with more <paramref name="metadata" />, and its
    /// <c>Program.cs</c>.
    /// </summary>
    public static SdkTestProject AddRocketsApp(
        this SdkTestProject project,
        string targetFramework,
        Generator generator,
        string include = "rockets.json",
        IReadOnlyDictionary<string, string?>? metadata = null,
        bool hook = true
    ) =>
        project
           .AddProject("app/app.csproj", project.CreateConsumer().Hosting(targetFramework).OpenApiClient(generator, include, metadata: metadata, hook: hook))
           .AddFile("app/rockets.json", RocketsApi.Document)
           .AddFile("app/Program.cs", Program(generator));

    /// <summary>
    /// The application: it registers the client, resolves it and writes the rocket it gets. The client is in
    /// <paramref name="namespace" />.
    /// </summary>
    public static string Program(Generator generator, string @namespace = "Throwaway.Clients") => generator switch
    {
        // Kiota's client is the class RocketsClient, with a request builder per path
        Generator.Kiota => Program("RocketsClient", "client.Rockets[id].GetAsync()", @namespace),
        // Refitter's client is the Refit interface IRocketsClient, with a method per operation
        Generator.Refitter => Program("IRocketsClient", "client.GetRocket(id)", @namespace),
        _ => throw new ArgumentOutOfRangeException(nameof(generator), generator, null),
    };

    /// <summary>
    /// <see cref="Program(Generator, string)" />, except that a call that fails writes the type and message of its exception instead of
    /// failing the application.
    /// </summary>
    public static string ProgramReportingFailure(Generator generator) =>
        Program(generator)
           .Replace("var rocket = await", "try\n{\n    var rocket = await", StringComparison.Ordinal)
           .TrimEnd()
           + "\n}\ncatch (Exception e)\n{\n    Console.WriteLine($\"{e.GetType().FullName}: {e.Message}\");\n}\n";

    private static string Program(string clientType, string getRocket, string @namespace) => $$"""
        using System;
        using Microsoft.Extensions.DependencyInjection;
        using Microsoft.Extensions.Hosting;
        using Microsoft.Extensions.Logging;
        using {{@namespace}};

        var builder = Host.CreateApplicationBuilder(args);
        builder.Logging.ClearProviders();
        builder.Services.AddRocketsClient();
        using var host = builder.Build();
        var client = host.Services.GetRequiredService<{{clientType}}>();
        var id = Guid.Parse("{{RocketsApi.RocketId}}");
        var rocket = await {{getRocket}};
        Console.WriteLine($"{nameof({{clientType}})}: {rocket!.Id} {rocket.SerialNumber}");
        """;
}
